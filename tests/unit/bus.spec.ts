import { createBus } from '../../src/core/bus'

describe('event bus', () => {
  it('emits dsk:* DOM events and hears events bubbling from elements', () => {
    const bus = createBus(document)
    const fn = vi.fn()
    const off = bus.on('node', fn)
    bus.emit('node', { id: 'a' })
    const el = document.createElement('div')
    document.body.appendChild(el)
    el.dispatchEvent(new CustomEvent('dsk:node', { detail: { id: 'b' }, bubbles: true }))
    expect(fn.mock.calls.map((c) => c[0].id)).toEqual(['a', 'b'])
    expect(fn.mock.calls[1]![1].target).toBe(el)
    off()
    bus.emit('node', {})
    expect(fn).toHaveBeenCalledTimes(2)
  })

  it('once, off, prefixed names and plain listeners', () => {
    const bus = createBus(document)
    const once = vi.fn()
    bus.once('dsk:x', once)
    bus.emit('x', 1)
    bus.emit('x', 2)
    expect(once).toHaveBeenCalledOnce()
    const plain = vi.fn()
    document.addEventListener('dsk:y', (e) => plain((e as CustomEvent).detail))
    bus.emit('y', 'detail')
    expect(plain).toHaveBeenCalledWith('detail')
    const fn = vi.fn()
    bus.on('z', fn)
    bus.on('z', fn)
    bus.emit('z')
    expect(fn).toHaveBeenCalledOnce()
    bus.off('z', fn)
    bus.emit('z')
    expect(fn).toHaveBeenCalledOnce()
  })
})
